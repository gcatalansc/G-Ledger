use sha2::{Digest, Sha256};
use std::{
    collections::BTreeSet,
    env,
    fmt::Write as _,
    fs,
    path::{Component, Path, PathBuf},
};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let root = manifest.parent().unwrap().parent().unwrap();
    let allowlist = manifest.join("resources.txt");
    println!("cargo:rerun-if-changed={}", allowlist.display());
    let list = fs::read_to_string(allowlist)?;
    let mut seen = BTreeSet::new();
    let mut index = String::from(
        "#[allow(clippy::unreadable_literal)] // Generated byte lengths.\nconst FILES: &[(&str, u64, &str)] = &[\n",
    );
    for relative in list
        .lines()
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
    {
        assert!(
            !relative.contains('\\')
                && Path::new(relative)
                    .components()
                    .all(|c| matches!(c, Component::Normal(_))),
            "unsafe resource path"
        );
        assert!(seen.insert(relative), "duplicate resource path");
        let mut path = root.to_path_buf();
        for component in Path::new(relative).components() {
            path.push(component);
            assert!(
                !fs::symlink_metadata(&path)?.file_type().is_symlink(),
                "resource path contains a symlink"
            );
        }
        let metadata = fs::symlink_metadata(&path)?;
        assert!(
            metadata.is_file() && metadata.len() <= 8 * 1024 * 1024,
            "invalid or oversized resource"
        );
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = fs::read(path)?;
        let mut digest = String::new();
        for byte in Sha256::digest(&bytes) {
            write!(digest, "{byte:02x}")?;
        }
        writeln!(index, "({relative:?}, {}, {digest:?}),", bytes.len())?;
    }
    assert!(
        !seen.is_empty() && seen.len() <= 2048,
        "resource count exceeds package budget"
    );
    index.push_str("];\n");
    fs::write(
        PathBuf::from(env::var("OUT_DIR")?).join("resource_index.rs"),
        index,
    )?;
    Ok(())
}
