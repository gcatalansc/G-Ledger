#[test]
fn ac_029_through_ac_033_markdown_is_deterministic_noncanonical_verified_and_visible() {
    let stream = stale_checkpoint_stream();
    let projection = ProjectStateProjection::rebuild(&stream).unwrap();
    let original_stream = stream.clone();
    let original_state = projection.state().clone();
    let request = MarkdownRenderRequest {
        artifact_id: id("generated-artifact:status"),
        uri: ResourceRef::parse("project-ledger://generated/status.md").unwrap(),
        renderer_version: "continuity-markdown-v1".to_owned(),
        privacy_profile: RendererPrivacyProfile::FullLocal,
        created_at: timestamp(40),
    };

    let first = MarkdownRenderer::render(&projection, &stream, &request).unwrap();
    let second = MarkdownRenderer::render(&projection, &stream, &request).unwrap();
    assert_eq!(first, second);
    assert_eq!(first.content.lines().next(), Some(WARNING));
    let mut prior = 0;
    for heading in HEADINGS {
        let position = first.content.find(heading).unwrap();
        assert!(position >= prior, "heading order changed at {heading}");
        prior = position;
    }
    assert!(first.content.contains("unknown:material"));
    assert!(first.content.contains("conflict:critical"));
    assert!(first.content.contains("INVALIDATED"));
    assert!(first.content.contains(r"C:\private\authority"));
    assert!(!first.content.contains("super-secret"));
    assert!(!first.content.contains("\n## injected"));
    assert_eq!(
        first.record.source_state_version,
        projection.state().state_version
    );
    assert_eq!(
        first.record.source_state_digest,
        projection.state().state_digest
    );
    assert_eq!(
        first.record.artifact_digest,
        sha256_bytes(first.content.as_bytes())
    );

    let mut shareable_request = request.clone();
    shareable_request.privacy_profile = RendererPrivacyProfile::Shareable;
    let shareable = MarkdownRenderer::render(&projection, &stream, &shareable_request).unwrap();
    assert!(!shareable.content.contains(r"C:\private\authority"));
    assert!(!shareable.content.contains("actor:test"));
    assert!(shareable.content.contains("unknown:material"));
    assert!(shareable.content.contains("conflict:critical"));

    let valid = verify_stream_and_artifact(&stream, &first.record, first.content.as_bytes());
    assert!(
        valid.valid,
        "unmodified generated view must verify: {valid:?}"
    );
    let mut invalid_contract = first.record.clone();
    invalid_contract.privacy_profile = "UNKNOWN_PROFILE".to_owned();
    let rejected_contract =
        verify_stream_and_artifact(&stream, &invalid_contract, first.content.as_bytes());
    assert!(!rejected_contract.valid);
    assert!(
        rejected_contract
            .findings
            .iter()
            .any(|finding| finding.code == AuditCode::GeneratedArtifactContractInvalid)
    );
    let modified = format!("{}\nmanual edit", first.content);
    let invalid = verify_stream_and_artifact(&stream, &first.record, modified.as_bytes());
    assert!(!invalid.valid);
    assert!(invalid.findings.iter().any(|finding| {
        finding.code == AuditCode::GeneratedArtifactModified
            && finding.subject_refs == vec![id("generated-artifact:status")]
    }));
    let regenerated = MarkdownRenderer::render(&projection, &stream, &request).unwrap();
    assert_eq!(regenerated, first);

    let audit = audit_projection(&projection);
    assert!(audit.findings.iter().any(|finding| {
        finding.code == AuditCode::CheckpointNotCurrent
            && finding
                .subject_refs
                .iter()
                .any(|subject| subject.as_str().starts_with("checkpoint:"))
    }));
    assert!(audit.findings.iter().any(|finding| {
        finding.code == AuditCode::CriticalConflictOpen
            && finding.subject_refs == vec![id("conflict:critical")]
    }));
    assert_eq!(stream, original_stream);
    assert_eq!(projection.state(), &original_state);
}

fn stale_checkpoint_stream() -> Vec<project_ledger_domain::EventEnvelope> {
    let mut stream = genesis();
    let checkpoint = command(
        20,
        stream.len() as u64,
        Command::CreateContinuityCheckpoint(CreateContinuityCheckpointPayload {
            reason: "handoff".to_owned(),
        }),
    );
    let drafts = ContinuityEngine::handle(&checkpoint, &stream).unwrap();
    append(&mut stream, &checkpoint, drafts);

    let unknown = with_digest(
        UnknownRecord {
            schema_version: SchemaVersion::V0_2_0,
            unknown_id: id("unknown:material"),
            subject_kind: "AUTHORITY".to_owned(),
            subject_ref: id("authority:pending"),
            field_path: "digest".to_owned(),
            statement: "authority digest requires review".to_owned(),
            criticality: UnknownCriticality::Material,
            status: UnknownStatus::Open,
            blocks: Vec::new(),
            required_evidence: vec!["authority digest".to_owned()],
            evidence_refs: Vec::new(),
            opened_at: timestamp(21),
            resolved_at: None,
            resolution_ref: None,
            provenance_ref: ResourceRef::parse("project-ledger://provenance/unknown/material")
                .unwrap(),
            digest: zero(),
        },
        |value, digest| value.digest = digest,
    );
    let record = command(
        21,
        stream.len() as u64,
        Command::RecordUnknown(RecordUnknownPayload { unknown }),
    );
    let base = ContinuityEngine::handle(&record, &stream).unwrap();
    let drafts = ContinuityEngine::extend_checkpoint_freshness(&record, &stream, base).unwrap();
    append(&mut stream, &record, drafts);

    let conflict_command = command(
        22,
        stream.len() as u64,
        Command::RecordNote(RecordNotePayload {
            kind: "AUDIT".to_owned(),
            text: "critical divergence".to_owned(),
            scope_ref: None,
        }),
    );
    append(
        &mut stream,
        &conflict_command,
        vec![EventDraft {
            event_id: event_id(22),
            event: Event::ConflictOpened(ConflictOpenedEvent {
                conflict: ConflictRecord {
                    schema_version: SchemaVersion::V0_2_0,
                    conflict_id: id("conflict:critical"),
                    kind: ConflictKind::SourceDivergence,
                    severity: Severity::Critical,
                    domain: "authority".to_owned(),
                    subject_refs: vec![id("authority:pending")],
                    source_refs: vec![
                        ResourceRef::parse("project-ledger://source/conflict/critical").unwrap(),
                    ],
                    status: ConflictStatus::Open,
                    required_action: "review canonical authority".to_owned(),
                    opened_at: timestamp(22),
                    resolved_at: None,
                    resolution_ref: None,
                },
            }),
            correlation_ref: id("correlation:markdown:conflict"),
            occurred_at: timestamp(22),
            recorded_at: timestamp(22),
        }],
    );
    stream
}

fn genesis() -> Vec<project_ledger_domain::EventEnvelope> {
    let command = command(
        1,
        0,
        Command::CreateProject(CreateProjectPayload { project: project() }),
    );
    vec![
        build_event(
            &command,
            1,
            None,
            EventDraft {
                event_id: event_id(1),
                event: Event::ProjectCreated(ProjectCreatedEvent { project: project() }),
                correlation_ref: id("correlation:markdown"),
                occurred_at: timestamp(1),
                recorded_at: timestamp(1),
            },
        )
        .unwrap(),
    ]
}

fn append(
    stream: &mut Vec<project_ledger_domain::EventEnvelope>,
    command: &CommandEnvelope,
    drafts: Vec<EventDraft>,
) {
    let mut previous = stream.last().map(|event| event.event_digest);
    for draft in drafts {
        let envelope = build_event(command, stream.len() as u64 + 1, previous, draft).unwrap();
        previous = Some(envelope.event_digest);
        stream.push(envelope);
    }
}

fn command(number: u8, expected: u64, payload: Command) -> CommandEnvelope {
    prepare_command(CommandDraft {
        schema_version: SchemaVersion::V0_2_0,
        command_id: CommandId::parse(&format!(
            "command:0198f8c8-7417-7fb0-b88f-0fe0c0a7df{number:02x}"
        ))
        .unwrap(),
        project_ref: project_id(),
        expected_state_version: expected,
        idempotency_key: id(&format!("idempotency:markdown:{number}")),
        actor: Actor {
            actor_id: id("actor:test"),
            actor_kind: ActorKind::Human,
            trust_level: TrustLevel::LocalUser,
            display_name: None,
        },
        command: payload,
        submitted_at: timestamp(u64::from(number)),
    })
    .unwrap()
}

